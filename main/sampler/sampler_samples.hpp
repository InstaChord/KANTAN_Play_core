enum class sample_category_t : uint8_t {
  kick,
  snare,
  tom,
  hihat,
  cymbal,
  percussion,
  bass,
  lead,
  pad,
  keys,
  pluck,
  mallet,
  voice,
  fx,
  waveform,
  count,
};

static constexpr const char* sample_category_names[] = {
  "Kick", "Snare", "Tom", "HiHat", "Cymbal", "Percussion",
  "Bass", "Lead", "Pad", "Keys", "Pluck", "Mallet", "Voice", "FX", "Waveform",
};
static constexpr size_t sample_category_count = (size_t)sample_category_t::count;
static_assert(sizeof(sample_category_names) / sizeof(sample_category_names[0]) == sample_category_count,
              "sample category name table mismatch");

// Categories with no remaining built-in entries are hidden. SD Card remains
// a separate final choice in the UI.
static constexpr sample_category_t sample_browser_categories[] = {
  sample_category_t::kick, sample_category_t::snare, sample_category_t::tom,
  sample_category_t::hihat, sample_category_t::cymbal,
  sample_category_t::percussion, sample_category_t::voice, sample_category_t::fx,
};
static constexpr size_t sample_browser_category_count =
  sizeof(sample_browser_categories) / sizeof(sample_browser_categories[0]);

static constexpr const char* sample_category_name(sample_category_t category)
{
  const size_t index = (size_t)category;
  return index < sample_category_count ? sample_category_names[index] : "Other";
}

struct sample_source_t {
  const char* name;        // Pad表示用の短い名前
  const uint8_t* data;     // WAVファイル先頭
  const uint8_t* size_sym; // サイズシンボル (アドレス値がサイズ)
  sample_category_t category = sample_category_t::fx;
  uint8_t base_note = 0xFF;  // 0xFF=自動解析。短尺シンセ素材はC4(60)を明示。
  uint16_t synth_loop_start_ms = 0;
  uint16_t synth_loop_end_ms = 0;
  uint16_t synth_loop_crossfade_ms = 0;
  uint16_t synth_release_ms = 120;
  uint16_t synth_attack_ms = 0;
  int16_t synth_tune_cents = 0;
  uint16_t default_gain_q8 = 256;
  size_t size(void) const { return (size_t)size_sym; }
  bool hasSynthPreset(void) const {
    return base_note <= 127 && synth_loop_end_ms > synth_loop_start_ms;
  }
};

